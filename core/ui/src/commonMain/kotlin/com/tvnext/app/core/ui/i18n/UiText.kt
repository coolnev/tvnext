/** App-owned observable locale. Reading it in a label recomposes that label on changes. */
object UiLocale {
    var language by mutableStateOf(UiLanguage.RUSSIAN)
}

/** Only UI keys pass through this function; provider titles and descriptions remain untouched. */
fun uiText(source: String, vararg arguments: Any?): String =
    UiTranslations.text(UiLocale.language, source, *arguments)

